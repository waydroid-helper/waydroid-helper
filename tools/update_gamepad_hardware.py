"""Generate the artwork family table from SDL's src/joystick/controller_list.h."""

import re
import sys
from collections import defaultdict
from pathlib import Path

FAMILIES = {
    "PS3Controller": "ps3",
    "PS4Controller": "ps4",
    "XInputPS4Controller": "ps4",
    "PS5Controller": "ps5",
    "XBox360Controller": "xbox-360",
    "XBoxOneController": "xbox-one",
    "SwitchInputOnlyController": "switch-pro",
    "SwitchProController": "switch-pro",
    "XInputSwitchController": "switch-pro",
    "SwitchJoyConLeft": "joycon-left",
    "SwitchJoyConRight": "joycon-right",
    "SwitchJoyConPair": "joycon-pair",
    "SteamController": "steam",
}


def generate(header):
    # Match active initializers only. SDL searches this array from the front,
    # so preserve its first match if two entries share a hardware ID.
    devices = {}
    for vendor, product, kind in re.findall(
        r"^\s*\{\s*MAKE_CONTROLLER_ID\(\s*(0x\w+),\s*(0x\w+)\s*\),"
        r"\s*k_eControllerType_(\w+)", header, re.MULTILINE
    ):
        devices.setdefault(int(vendor, 16) << 16 | int(product, 16), kind)
    if not devices:
        raise ValueError("No SDL controller IDs found")
    families = defaultdict(list)
    for device_id, kind in sorted(devices.items()):
        if kind in FAMILIES:
            families[FAMILIES[kind]].append(f"0x{device_id:08x}")
    notice = header.partition("/*")[2].partition("*/")[0].strip()
    lines = [
        '"""Artwork families derived from Valve\'s controller list in SDL release-3.4.0.',
        "",
        "Generated by tools/update_gamepad_hardware.py from src/joystick/controller_list.h.",
        "",
        notice,
        '"""',
        "",
        "DEVICE_IDS = {",
    ]
    for family, ids in sorted(families.items()):
        lines.append(f'    "{family}": {{')
        for i in range(0, len(ids), 6):
            lines.append("        " + ", ".join(ids[i : i + 6]) + ",")
        lines.append("    },")
    return "\n".join([*lines, "}",""])


if __name__ == "__main__":
    print(generate(Path(sys.argv[1]).read_text()), end="")
